"""The M4 orchestration layer.

Reached from the backend through exactly one adapter,
`app/ai/orchestrated_engine.py`, which implements `app.ai.ports.AiEngine`.
Nothing in `app/api` or `app/services` imports this package directly, and
`tests/test_layering.py` enforces that from the other side — the whole value of
a three-callable port is lost the first time a route reaches past it.

What is here:

    RouterInput  -> IntentRouter.aclassify()   -> IntentDecision
    question     -> QueryRewriter.arewrite()   -> RewriteResult
    question     -> AskWorkflow.run()          -> StreamEvent stream
    document     -> SummaryWorkflow.run()      -> StreamEvent stream
    DraftParams  -> DraftWorkflow.run()        -> StreamEvent stream

Retrieval is bge-m3 (dense + learned sparse) into Qdrant with server-side RRF,
reranked by bge-reranker-v2-m3, expanded child -> parent, assembled as fenced
data, generated by Sonnet 5, and verified by the FR-21/FR-22 citation gate.

Ask retrieves once and streams token by token. Summary retrieves once *per
template field* and emits a field at a time. Draft retrieves once and emits a
section at a time. Those three shapes are not stylistic — see each module's
docstring for why its topology is the one its feature needs.

Importing this package does not import torch, Qdrant or LangChain — the heavy
pieces load behind `build_retriever()` and inside the workflow constructors, so
tests can inject fakes without downloading a model.
"""


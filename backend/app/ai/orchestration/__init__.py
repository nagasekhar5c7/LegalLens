def build_retriever(settings: RouterSettings | None = None) -> Retriever:
    """The real retrieval stack: bge-m3 + Qdrant + bge-reranker-v2-m3.

    Delegates to `retrieval.factory`, which caches the store and both models
    per process. That is not an optimisation: a local Qdrant client takes an
    **exclusive lock** on its directory, so constructing a second one for the
    same path raises "Storage folder is already accessed by another instance" —
    which a second call here, or a turn racing the indexer, would hit.

    Imported inside the function so that importing `app.ai.orchestration` stays
    free of torch and qdrant-client; the models themselves load on first use.
    """
    from app.ai.orchestration.retrieval import factory

    return factory.build_retriever(settings)


